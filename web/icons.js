export function iconSvg(name, size = 16) {
  const paths = ICONS[name];
  if (!paths) throw new Error(`no icon named ${name}`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths}</svg>`;
}

export function renderIcons(root) {
  for (const slot of root.querySelectorAll("[data-icon]")) slot.innerHTML = iconSvg(slot.dataset.icon, Number(slot.dataset.size) || 16);
}

if (typeof document !== "undefined") renderIcons(document);
